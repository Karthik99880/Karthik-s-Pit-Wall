// Regenerates src/lib/circuitPaths.ts from bacinger/f1-circuits: node scripts/gen-circuit-paths.mjs
import { writeFileSync } from 'node:fs';

const IDS = {
  bahrain: 'bh-2002', jeddah: 'sa-2021', albert_park: 'au-1953', suzuka: 'jp-1962', shanghai: 'cn-2004',
  miami: 'us-2022', imola: 'it-1953', monaco: 'mc-1929', villeneuve: 'ca-1978', catalunya: 'es-1991',
  red_bull_ring: 'at-1969', silverstone: 'gb-1948', hungaroring: 'hu-1986', spa: 'be-1925', zandvoort: 'nl-1948',
  monza: 'it-1922', baku: 'az-2016', marina_bay: 'sg-2008', americas: 'us-2012', rodriguez: 'mx-1962',
  interlagos: 'br-1940', vegas: 'us-2023', losail: 'qa-2004', yas_marina: 'ae-2009', madring: 'es-2026',
};
const W = 300, H = 200, PAD = 10;

const geo = await (await fetch('https://raw.githubusercontent.com/bacinger/f1-circuits/master/f1-circuits.geojson')).json();
const byId = Object.fromEntries(geo.features.map(f => [f.properties.id, f.geometry.coordinates]));

const out = {};
for (const [ergast, id] of Object.entries(IDS)) {
  const c = byId[id];
  if (!c) throw new Error(`missing ${id}`);
  const k = Math.cos((c[0][1] * Math.PI) / 180);
  const pts = c.map(([lon, lat]) => [lon * k, -lat]);
  const xs = pts.map(p => p[0]), ys = pts.map(p => p[1]);
  const x0 = Math.min(...xs), y0 = Math.min(...ys);
  const w = Math.max(...xs) - x0, h = Math.max(...ys) - y0;
  const s = Math.min((W - 2 * PAD) / w, (H - 2 * PAD) / h);
  const ox = (W - w * s) / 2, oy = (H - h * s) / 2;
  out[ergast] = 'M' + pts.map(([x, y]) => `${((x - x0) * s + ox).toFixed(1)} ${((y - y0) * s + oy).toFixed(1)}`).join('L') + 'Z';
}

writeFileSync('src/lib/circuitPaths.ts',
  `// Generated by scripts/gen-circuit-paths.mjs. Track outlines (c) 2019-2025 Tomislav Bacinger, MIT, github.com/bacinger/f1-circuits\n` +
  `export const CIRCUIT_VIEWBOX = '0 0 ${W} ${H}';\n` +
  `export const CIRCUIT_PATHS: Record<string, string> = ${JSON.stringify(out, null, 1)};\n`);
console.log(Object.keys(out).length, 'circuits');
